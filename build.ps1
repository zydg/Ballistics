param(
  [string]$GameDir = '',
  [string]$OutDir  = '',
  [string]$Version = '1.0.0',
  [ValidateSet('Release', 'Debug')][string]$Config = 'Release',
  [switch]$Install,
  [switch]$Package
)
$ErrorActionPreference = 'Stop'

if (!$OutDir)  { $OutDir  = Join-Path $PSScriptRoot 'out' }
if (!$GameDir) { throw 'pass -GameDir <your SPT install>, e.g. -GameDir "C:\SPT"' }

$src = Join-Path $PSScriptRoot 'src'
if (!(Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }
Copy-Item (Join-Path $src '*.cs') $OutDir -Force

$managed = Join-Path $GameDir 'EscapeFromTarkov_Data\Managed'
$core = Join-Path $GameDir 'BepInEx\core'
if (!(Test-Path $managed)) { throw "Managed dir not found: $managed (pass -GameDir)" }

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (!(Test-Path $csc)) { throw "csc.exe not found: $csc" }

$tag = 'release'
try { $tag = (& git -C $PSScriptRoot rev-parse --short HEAD 2>$null); if (!$tag) { $tag = 'release' } } catch { }

$av = $Version
if ($Version -match '^\d+\.\d+\.\d+$') { $av = $Version + '.0' }

$versionCs = '[assembly: System.Reflection.AssemblyVersion("' + $av + '")]' + [char]10 +
             '[assembly: System.Reflection.AssemblyFileVersion("' + $av + '")]' + [char]10 +
             '[assembly: System.Reflection.AssemblyInformationalVersion("' + $Version + '")]' + [char]10 +
             'namespace Dsh.BallisticsDebug.Impl { public static class BuildInfo { public const string Tag = "' + $tag + '"; } }' + [char]10 +
             'namespace Dsh.BallisticsDebug.Loader { public static class LoaderBuildInfo { public const string Version = "' + $Version + '"; } }'
[IO.File]::WriteAllText((Join-Path $OutDir 'Version.cs'), $versionCs, (New-Object Text.UTF8Encoding($false)))

$common = @('/target:library', '/nologo', '/optimize+',
  ('/r:"' + (Join-Path $managed 'netstandard.dll') + '"'),
  ('/r:"' + (Join-Path $managed 'UnityEngine.dll') + '"'),
  ('/r:"' + (Join-Path $managed 'UnityEngine.PhysicsModule.dll') + '"'),
  ('/r:"' + (Join-Path $managed 'UnityEngine.CoreModule.dll') + '"'),
  ('/r:"' + (Join-Path $managed 'UnityEngine.IMGUIModule.dll') + '"'),
  ('/r:"' + (Join-Path $managed 'UnityEngine.InputLegacyModule.dll') + '"'),
  ('/r:"' + (Join-Path $managed 'UnityEngine.TextRenderingModule.dll') + '"'),
  ('/r:"' + (Join-Path $core 'BepInEx.dll') + '"'),
  ('/r:"' + (Join-Path $core '0Harmony.dll') + '"'))


# 内置英文表从 lang/en.json 生成，保证翻译只有一个来源
$enJson = Join-Path $PSScriptRoot 'lang\en.json'
if (!(Test-Path $enJson)) { throw "lang/en.json not found: $enJson" }
$en = (Get-Content $enJson -Raw -Encoding UTF8 | ConvertFrom-Json)
$gen = New-Object System.Text.StringBuilder
[void]$gen.AppendLine('// <auto-generated> build.ps1 <- lang/en.json，请勿手改 </auto-generated>')
[void]$gen.AppendLine('using System.Collections.Generic;')
[void]$gen.AppendLine('')
[void]$gen.AppendLine('namespace Dsh.BallisticsDebug.Shared')
[void]$gen.AppendLine('{')
[void]$gen.AppendLine('    internal static class LangEn')
[void]$gen.AppendLine('    {')
[void]$gen.AppendLine('        internal static readonly Dictionary<string, string> Map = new Dictionary<string, string>(128)')
[void]$gen.AppendLine('        {')
foreach ($prop in ($en.PSObject.Properties | Sort-Object Name)) {
  $k = $prop.Name.Replace('\', '\\').Replace('"', '\"')
  $v = $prop.Value.ToString().Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
  [void]$gen.AppendLine('            { "' + $k + '", "' + $v + '" },')
}
[void]$gen.AppendLine('        };')
[void]$gen.AppendLine('    }')
[void]$gen.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $OutDir 'LangEn.g.cs'), $gen.ToString(), (New-Object Text.UTF8Encoding($false)))
$dll = Join-Path $OutDir 'Ballistics.dll'
$bytes = Join-Path $OutDir 'BallisticsImpl.bytes'

# csc 用相对文件名，必须先把工作目录切到输出目录（源文件已复制到那里）
Push-Location $OutDir
try {
  if ($Config -eq 'Release') {
    # single static dll: shell + implementation in one assembly, no hot reload
    & $csc ($common + @('/define:STATIC_BUILD', ('/out:' + $dll), 'Loader.cs', 'Impl.cs', 'Lang.cs', 'LangEn.g.cs', 'Version.cs'))
    if ($LASTEXITCODE -ne 0) { throw 'release build failed' }
    if (Test-Path $bytes) { Remove-Item $bytes -Force }
    'built Release (single dll) v=' + $Version + ' tag=' + $tag
  }
  else {
    # debug: shell dll + hot-reloadable implementation bytes
    & $csc ($common + @(('/out:' + $dll), 'Loader.cs', 'Lang.cs', 'LangEn.g.cs', 'Version.cs'))
    if ($LASTEXITCODE -ne 0) { throw 'shell build failed' }
    & $csc ($common + @(('/out:' + $bytes), 'Impl.cs', 'Lang.cs', 'LangEn.g.cs', 'Version.cs'))
    if ($LASTEXITCODE -ne 0) { throw 'impl build failed' }
    'built Debug (shell + bytes) v=' + $Version + ' tag=' + $tag
  }
}
finally { Pop-Location }

if ($Install) {
  $legacy = Join-Path $GameDir 'BepInEx\plugins\BallisticsDebug'
  $legacy2 = Join-Path $GameDir 'BepInEx\plugins\Ballistics'
  $legacy3 = Join-Path $GameDir 'BepInEx\plugins\弹道学'
  if (Test-Path $legacy) { Remove-Item $legacy -Recurse -Force; 'removed legacy folder: ' + $legacy }
  if (Test-Path $legacy2) { Remove-Item $legacy2 -Recurse -Force; 'removed previous folder: ' + $legacy2 }
  if (Test-Path $legacy3) { Remove-Item $legacy3 -Recurse -Force; 'removed legacy cn folder: ' + $legacy3 }
  $pluginDir = Join-Path $GameDir 'BepInEx\plugins\Ballistics'
  if (!(Test-Path $pluginDir)) { New-Item -ItemType Directory -Path $pluginDir | Out-Null }
  Copy-Item $dll $pluginDir -Force
  $implDir = Join-Path $pluginDir 'Impl'
  if ($Config -eq 'Release') {
    if (Test-Path $implDir) { Remove-Item $implDir -Recurse -Force }
  }
  else {
    if (!(Test-Path $implDir)) { New-Item -ItemType Directory -Path $implDir | Out-Null }
    Copy-Item $bytes (Join-Path $implDir 'BallisticsImpl.bytes') -Force
  }
  $langSrc = Join-Path $PSScriptRoot 'lang'
  if (Test-Path $langSrc) {
    $langDst = Join-Path $pluginDir 'Lang'
    if (!(Test-Path $langDst)) { New-Item -ItemType Directory -Path $langDst | Out-Null }
    Copy-Item (Join-Path $langSrc '*.json') $langDst -Force
  }
  'installed -> ' + $pluginDir + ' (' + $Config + ')'
}

if ($Package) {
  $pkgRoot = Join-Path $OutDir 'pkg'
  if (Test-Path $pkgRoot) { Remove-Item $pkgRoot -Recurse -Force }
  $pluginOut = Join-Path $pkgRoot 'BepInEx\plugins\Ballistics'
  New-Item -ItemType Directory -Path $pluginOut -Force | Out-Null
  Copy-Item $dll $pluginOut -Force
  if ($Config -eq 'Debug') {
    $implOut = Join-Path $pluginOut 'Impl'
    New-Item -ItemType Directory -Path $implOut -Force | Out-Null
    Copy-Item $bytes (Join-Path $implOut 'BallisticsImpl.bytes') -Force
  }
  $langSrc = Join-Path $PSScriptRoot 'lang'
  if (Test-Path $langSrc) {
    $langOut = Join-Path $pluginOut 'Lang'
    if (!(Test-Path $langOut)) { New-Item -ItemType Directory -Path $langOut | Out-Null }
    Copy-Item (Join-Path $langSrc '*.json') $langOut -Force
  }
  $dist = Join-Path $PSScriptRoot 'dist'
  if (!(Test-Path $dist)) { New-Item -ItemType Directory -Path $dist | Out-Null }
  $zip = Join-Path $dist ('Ballistics-' + $Version + '-' + $Config + '.zip')
  if (Test-Path $zip) { Remove-Item $zip -Force }
  Compress-Archive -Path (Join-Path $pkgRoot '*') -DestinationPath $zip
  'packaged -> ' + $zip
}
